// Writes contracts/test/PqFixture.sol: a real SLH-DSA-SHA2-128s key and a signature over the post-quantum
// challenge message for the test learner, as the fork tests deploy it on Arc testnet. Rerun if the
// test's deployment order, learner address or chain changes; the tests check the predicted addresses.
import { writeFile } from 'node:fs/promises';
import { encodePacked, getAddress, getContractAddress, toHex } from 'viem';
import { slh_dsa_sha2_128s as slh } from '@noble/post-quantum/slh-dsa.js';

const CHAIN_ID = 5042002n; // Arc testnet, the fork target in contracts/foundry.toml
const TEST_CONTRACT = '0x7FA9385bE102ac3EAc297483Dd6233D62b3e1496'; // Foundry's default test address
const ALICE = getAddress('0x00000000000000000000000000000000000a11ce');
const checker = getContractAddress({ from: TEST_CONTRACT, nonce: 3n }); // registry 1, vault checker 2, PQ checker 3

const message = encodePacked(
  ['string', 'uint256', 'address', 'address'],
  ['Arc Lab post-quantum challenge', CHAIN_ID, checker, ALICE],
);
const { publicKey, secretKey } = slh.keygen(crypto.getRandomValues(new Uint8Array(48)));
const sig = slh.sign(Buffer.from(message.slice(2), 'hex'), secretKey);
if (!slh.verify(sig, Buffer.from(message.slice(2), 'hex'), publicKey)) throw new Error('local verify failed');

const out = `// SPDX-License-Identifier: MIT
pragma solidity 0.8.30;

// Generated by scripts/make-pq-fixture.mjs. Test-only key; the secret key was discarded.
address constant PQ_CHECKER = ${checker};
address constant PQ_LEARNER = ${ALICE};
bytes constant PQ_VK = hex"${toHex(publicKey).slice(2)}";
bytes constant PQ_SIG = hex"${toHex(sig).slice(2)}";
`;
await writeFile(new URL('../contracts/test/PqFixture.sol', import.meta.url), out);
console.log(`PqFixture.sol written: checker ${checker}, learner ${ALICE}, sig ${sig.length} bytes`);
